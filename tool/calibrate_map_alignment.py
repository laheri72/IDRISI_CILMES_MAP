"""Measure correspondence between the Arabic and English map previews.

Requires opencv-python-headless, numpy, and scipy. This is an offline
calibration aid; the Flutter app uses checked-in control points.
"""

from pathlib import Path
import sys

import cv2
import numpy as np
from scipy.interpolate import RBFInterpolator


ROOT = Path(__file__).resolve().parents[1]
MAPS = ROOT / "assets" / "maps" / "previews"
AR = MAPS / "idrisi_map_ar.webp"
EN = MAPS / "idrisi_map_en.webp"


def main() -> None:
    ar = cv2.imread(str(AR), cv2.IMREAD_GRAYSCALE)
    en = cv2.imread(str(EN), cv2.IMREAD_GRAYSCALE)
    sift = cv2.SIFT_create(nfeatures=25000)
    ar_features, ar_descriptors = sift.detectAndCompute(ar, None)
    en_features, en_descriptors = sift.detectAndCompute(en, None)
    matcher = cv2.BFMatcher()
    pairs = matcher.knnMatch(ar_descriptors, en_descriptors, k=2)
    good = [m for m, n in pairs if m.distance < 0.7 * n.distance]
    ar_pts = np.float32([ar_features[m.queryIdx].pt for m in good])
    en_pts = np.float32([en_features[m.trainIdx].pt for m in good])
    H, inliers = cv2.findHomography(ar_pts, en_pts, cv2.RANSAC, 5)
    inliers = inliers.ravel().astype(bool)
    mapped = cv2.perspectiveTransform(ar_pts[:, None, :], H)[:, 0, :]
    residuals = np.linalg.norm(mapped - en_pts, axis=1)
    print(f"features: Arabic={len(ar_features)}, English={len(en_features)}")
    print(f"matches={len(good)}, inliers={inliers.sum()}")
    print("homography:\n", H)
    print("inlier residual px:", np.percentile(residuals[inliers], [50, 90, 99]))
    for row in range(2):
        for col in range(4):
            mask = (
                inliers
                & (ar_pts[:, 0] >= col * ar.shape[1] / 4)
                & (ar_pts[:, 0] < (col + 1) * ar.shape[1] / 4)
                & (ar_pts[:, 1] >= row * ar.shape[0] / 2)
                & (ar_pts[:, 1] < (row + 1) * ar.shape[0] / 2)
            )
            print(f"cell {col},{row}: {mask.sum()} matches, p50/p90={np.percentile(residuals[mask], [50, 90]) if mask.any() else None}")

    source = ar_pts[inliers]
    target = en_pts[inliers]
    rng = np.random.default_rng(7)
    order = rng.permutation(len(source))
    train, test = order[:int(len(order) * .75)], order[int(len(order) * .75):]
    train_h, _ = cv2.findHomography(source[train], target[train], 0)
    train_prediction = cv2.perspectiveTransform(source[train, None], train_h)[:, 0]
    test_prediction = cv2.perspectiveTransform(source[test, None], train_h)[:, 0]
    global_error = np.linalg.norm(test_prediction - target[test], axis=1)
    print("holdout global p50/p90:", np.percentile(global_error, [50, 90]))
    for smooth in [1, 5, 20, 100]:
        correction = RBFInterpolator(source[train], target[train] - train_prediction,
                                     neighbors=30, smoothing=smooth)
        corrected = test_prediction + correction(source[test])
        error = np.linalg.norm(corrected - target[test], axis=1)
        print(f"holdout local smooth={smooth} p50/p90:", np.percentile(error, [50, 90]))
        if smooth == 20:
            for cols, rows in [(9, 5), (17, 9), (33, 17), (49, 25)]:
                xs = np.linspace(0, ar.shape[1], cols)
                ys = np.linspace(0, ar.shape[0], rows)
                grid_points = np.array([(x, y) for y in ys for x in xs])
                grid = correction(grid_points).reshape(rows, cols, 2)
                cx = np.clip(source[test, 0] / ar.shape[1] * (cols - 1), 0, cols - 1)
                cy = np.clip(source[test, 1] / ar.shape[0] * (rows - 1), 0, rows - 1)
                ix = np.minimum(cx.astype(int), cols - 2)
                iy = np.minimum(cy.astype(int), rows - 2)
                fx = (cx - ix)[:, None]
                fy = (cy - iy)[:, None]
                interp = ((1-fx)*(1-fy)*grid[iy, ix]
                          + fx*(1-fy)*grid[iy, ix+1]
                          + (1-fx)*fy*grid[iy+1, ix]
                          + fx*fy*grid[iy+1, ix+1])
                grid_error = np.linalg.norm(test_prediction + interp - target[test], axis=1)
                print(f"holdout grid {cols}x{rows} p50/p90:", np.percentile(grid_error, [50, 90]))

    if "--write" in sys.argv:
        cols, rows = 33, 17
        correction = RBFInterpolator(source, target - mapped[inliers],
                                     neighbors=30, smoothing=20)
        xs = np.linspace(0, ar.shape[1], cols)
        ys = np.linspace(0, ar.shape[0], rows)
        grid_points = np.array([(x, y) for y in ys for x in xs])
        projected = cv2.perspectiveTransform(grid_points.astype(np.float32)[:, None], H)[:, 0]
        en_points = projected + correction(grid_points)
        en_points[:, 0] /= en.shape[1]
        en_points[:, 1] /= en.shape[0]
        output = ROOT / "lib" / "utils" / "map_alignment_data.dart"
        lines = [
            "// Generated by tool/calibrate_map_alignment.py --write.",
            "// Arabic normalized grid nodes map to English normalized positions.",
            f"const int mapAlignmentColumns = {cols};",
            f"const int mapAlignmentRows = {rows};",
            "const List<double> mapAlignmentEnglishNodes = [",
        ]
        for row in range(rows):
            parts = [f"{x:.8f}, {y:.8f}" for x, y in en_points[row * cols:(row + 1) * cols]]
            lines.append("  " + ", ".join(parts) + ",")
        lines.append("];")
        output.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"wrote {output}")


if __name__ == "__main__":
    main()
